"""Build design-a.html (a static page any browser can open) from Main.dc.html.

Main.dc.html is the Claude Design source: {{accent}} holes and an <sc-for> slot loop that only the
canvas runtime renders. This script fills them the way the design's renderVals() does.

Usage: python3 extension/docs/design/build.py
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ACCENT = '#0057B8'  # data-props default of "accent"
# The same sample day as renderVals(): 09:00-12:00 in 10-minute slots
TAKEN = ['09:00', '09:10', '09:30', '10:00', '10:10', '10:40', '11:00', '11:20', '11:30']
SELECTED = '09:50'

src = (HERE / 'Main.dc.html').read_text(encoding='utf-8')
helmet = re.search(r'<helmet>(.*?)</helmet>', src, re.S).group(1).strip()
body = re.search(r'</helmet>\s*(.*?)\s*</x-dc>', src, re.S).group(1)

loop = re.search(r'<sc-for[^>]*>(.*?)</sc-for>', body, re.S)
cell = {kind: re.search(r'<sc-if value="\{\{s\.%s\}\}"[^>]*>(.*?)</sc-if>' % kind, loop.group(1), re.S).group(1)
        for kind in ('taken', 'free', 'selected')}
cells = []
for minutes in range(9 * 60, 12 * 60, 10):
    time = '%02d:%02d' % (minutes // 60, minutes % 60)
    kind = 'selected' if time == SELECTED else 'taken' if time in TAKEN else 'free'
    cells.append(cell[kind].replace('{{s.time}}', time))
body = body[:loop.start()] + '\n          '.join(cells) + body[loop.end():]
body = body.replace('{{accent}}', ACCENT)

left = re.findall(r'\{\{[^}]*\}\}|<sc-|<dc-', body)
if left:
    raise SystemExit(f'Unfilled template parts: {sorted(set(left))}. Update build.py for the new design.')

(HERE / 'design-a.html').write_text(f'''<!doctype html>
<html lang="uk">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>A · Державний — e-Consul Helper</title>
<!-- Generated by build.py from Main.dc.html (Claude Design). Do not edit by hand. -->
{helmet}
</head>
<body style="background: #EEF2F7">
{body}
</body>
</html>
''', encoding='utf-8')
print(f'design-a.html: {len(cells)} slots, accent {ACCENT}')
